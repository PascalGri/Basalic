// Deterministic local derivatives only. Original assets are never overwritten.
import { readFile, writeFile, mkdir, rm, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { loadEnv } from 'vite';
import { load } from 'cheerio';
import { properties } from '../src/data.js';
import { propertyGalleries } from '../src/property-galleries.js';
import { pagesOutput, readPagesConfig } from './pages-config.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'public/assets');
const pages = process.argv.includes('--pages') ? readPagesConfig() : null;
const outputDir = join(root, pages ? pagesOutput : 'dist');
if (pages) {
  process.env.BASALIC_PAGES_BASE = pages.base;
  process.env.BASALIC_PAGES_ORIGIN = pages.origin;
}
const manifestPath = join(root, 'src/media-manifest.js');
const widths = [320, 640, 960, 1440];
const variantSignature = 'webp-q82-effort5-widths320,640,960,1440-v1';
const socialSignature = 'aurora-webp86-v2';
const sha256 = value => createHash('sha256').update(value).digest('hex');
const escapeXml = value => String(value ?? '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[char]));

async function writeIfChanged(path, data) {
  const buffer = Buffer.isBuffer(data) ? data : Buffer.from(data);
  try { if ((await readFile(path)).equals(buffer)) return false; } catch {}
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, buffer);
  return true;
}

async function previousManifest() {
  try {
    const source = await readFile(manifestPath, 'utf8');
    const marker = 'export const mediaManifest = ';
    return JSON.parse(source.slice(source.indexOf(marker) + marker.length).replace(/;\s*$/, ''));
  } catch { return {}; }
}

async function exists(path) {
  try { return (await stat(path)).size > 0; } catch { return false; }
}

async function writeManifest(manifest) {
  return writeIfChanged(manifestPath, `// Generated by scripts/prepare-media.mjs. Do not edit by hand.\nexport const mediaManifest = ${JSON.stringify(manifest, null, 2)};\n`);
}

function configFromEnvironment() {
  const loaded = loadEnv(process.env.NODE_ENV || 'production', root, '');
  const value = process.env.SITE_URL || process.env.VITE_SITE_URL || loaded.SITE_URL || loaded.VITE_SITE_URL || '';
  let siteUrl = '';
  if (value) {
    let url;
    try { url = new URL(value); } catch { throw new Error('SITE_URL muss eine absolute HTTP(S)-Origin sein.'); }
    if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password || url.search || url.hash || url.pathname !== '/') throw new Error('SITE_URL muss eine HTTP(S)-Origin ohne Zugangsdaten, Pfad, Query oder Fragment sein.');
    siteUrl = url.origin;
  }
  const flag = process.env.ALLOW_INDEXING ?? process.env.VITE_ALLOW_INDEXING ?? loaded.ALLOW_INDEXING ?? loaded.VITE_ALLOW_INDEXING ?? '';
  return { siteUrl, allowIndexing: Boolean(siteUrl) && ['true', '1'].includes(String(flag).toLowerCase()) };
}

async function prepareImages() {
  const previous = await previousManifest();
  const names = [...new Set([
    'hero-original', 'senad-basalic',
    ...properties.map(property => property.image).filter(Boolean),
    ...['mietverwaltung', 'finanzierung', 'absicherung', 'altersvorsorge'].map(name => `services/${name}`),
    ...Object.values(propertyGalleries).flat().map(photo => photo.src.replace(/^\/assets\//, '').replace(/\.webp$/, '')),
  ])].sort();
  const images = {};
  let outputs = 0;
  for (const name of names) {
    if (!/^[a-z0-9][a-z0-9/_-]*$/i.test(name)) throw new Error(`Unsicherer Assetname: ${name}`);
    const original = await readFile(join(assets, `${name}.webp`));
    const sourceSha256 = sha256(original);
    const metadata = await sharp(original).metadata();
    if (!metadata.width || !metadata.height) throw new Error(`Fehlende Bildmaße: ${name}`);
    const variantWidths = [...new Set([...widths.filter(width => width <= metadata.width), Math.min(metadata.width, 1440)])].sort((a, b) => a - b);
    const cached = previous.images?.[name];
    if (previous.variantSignature === variantSignature && cached?.sourceSha256 === sourceSha256
      && JSON.stringify(cached.variants.map(variant => variant.width)) === JSON.stringify(variantWidths)
      && (await Promise.all(cached.variants.map(variant => exists(join(root, 'public', variant.src))))).every(Boolean)) {
      images[name] = cached;
      continue;
    }
    const variants = [];
    for (const width of variantWidths) {
      const src = `/assets/responsive/${name}-${width}.webp`;
      const result = await sharp(original).resize({ width, withoutEnlargement: true }).webp({ quality: 82, effort: 5 }).toBuffer({ resolveWithObject: true });
      if (await writeIfChanged(join(root, 'public', src), result.data)) outputs++;
      variants.push({ src, width: result.info.width, height: result.info.height });
    }
    images[name] = { src: `/assets/${name}.webp`, width: metadata.width, height: metadata.height, sourceSha256, variants };
  }
  const manifest = { version: 1, variantSignature, seo: configFromEnvironment(), images, social: previous.social || {} };
  await writeManifest(manifest);
  return { manifest, outputs };
}

